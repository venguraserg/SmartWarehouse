namespace SmartWarehouse.Domain.Enums;

/// <summary>
/// На каком основании позиция числится за сотрудником.
/// </summary>
public enum CustodyKind
{
    /// <summary>
    /// «Выдано в работу»: кладовщик выдал со склада. В 1С вещь остаётся на МОЛ кладовщика,
    /// в бухгалтерии её списывает кладовщик по отчёту сотрудника об использовании.
    /// </summary>
    Work = 0,

    /// <summary>
    /// Прежний «подотчёт по 1С» (МОЛ — сам сотрудник). Больше не оформляется: такие остатки перенесены на склад
    /// в «Место не указано», а МОЛ стал пометкой партии (<see cref="Entities.Batch.MolId"/>). Остаётся для истории.
    /// </summary>
    Official = 1
}
