namespace SmartWarehouse.Domain.Enums;

/// <summary>Роли пользователя. У одного пользователя может быть несколько ролей (флаги).</summary>
[Flags]
public enum UserRole
{
    None = 0,

    /// <summary>Сотрудник: свой подотчёт, просмотр остатков, свои акты на списание.</summary>
    Employee = 1,

    /// <summary>Руководитель: подотчёт и акты подчинённых, утверждение актов.</summary>
    Manager = 2,

    /// <summary>Кладовщик: приход, выдача, возврат, перемещение, корректировка, номенклатура, склады.</summary>
    Storekeeper = 4,

    /// <summary>Администратор: всё, а также учётные записи и справочник сотрудников.</summary>
    Admin = 8
}
