namespace SmartWarehouse.Domain.Enums;

/// <summary>Вид документа «куда израсходовано».</summary>
public enum ActKind
{
    /// <summary>
    /// Акт на списание (АС-…): сотрудник списывает «подотчёт по 1С», утверждает руководитель —
    /// проводится списание.
    /// </summary>
    WriteOff = 0,

    /// <summary>
    /// Отчёт об использовании (ОИ-…): что из выданного «в работу» израсходовано и куда. Вносит сотрудник
    /// или кладовщик, подтверждает кладовщик. Подтверждённое ждёт сводного акта кладовщика за месяц
    /// (до тех пор — в резерве); вне учёта списывается сразу при подтверждении.
    /// </summary>
    UsageReport = 1
}
